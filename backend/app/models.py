"""Shared Pydantic models for the AccessPilot API.

Each finding carries a `source` that tells the user where it came from:
- "deterministic": computed by rule-based checks (always trustworthy)
- "ai": generated by the configured AI provider (advisory only)
- "human": flagged as needing human review (e.g. semantic reading order)
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field, field_validator


class Severity(str, Enum):
    ERROR = "error"
    WARNING = "warning"
    INFO = "info"


class FindingSource(str, Enum):
    DETERMINISTIC = "deterministic"
    AI = "ai"
    HUMAN = "human"


class DocumentKind(str, Enum):
    PDF = "pdf"
    DOCX = "docx"
    PPTX = "pptx"


class BlockType(str, Enum):
    HEADING = "heading"
    PARAGRAPH = "paragraph"
    IMAGE = "image"
    LINK = "link"
    TABLE = "table"
    LIST = "list"
    OTHER = "other"


class Block(BaseModel):
    """A single extracted document block. Position is 1-indexed."""

    index: int = Field(..., ge=1)
    kind: BlockType = BlockType.OTHER
    text: str = ""
    heading_level: int | None = None
    has_alt_text: bool | None = None
    link_label: str | None = None
    page: int | None = None
    slide: int | None = None


class Finding(BaseModel):
    """One concrete accessibility issue detected in a document."""

    id: str = Field(..., description="Stable finding identifier (rule id + index).")
    rule: str = Field(..., description="Short rule identifier, e.g. 'headings.hierarchy'")
    severity: Severity
    source: FindingSource
    location: str = Field(..., description="Human-readable location, e.g. 'page 3', 'slide 2'")
    description: str
    detail: str = Field("", description="More context, e.g. offending text")
    remediation: str
    wcag_ref: str = Field("", description="Optional WCAG 2.x reference code")
    block_index: int | None = None
    suggestion: str | None = Field(
        None, description="Concrete before/after suggestion if applicable"
    )


class SummaryStats(BaseModel):
    errors: int = 0
    warnings: int = 0
    info: int = 0
    total_blocks: int = 0


class DocumentMeta(BaseModel):
    filename: str
    kind: DocumentKind
    size_bytes: int
    num_blocks: int = 0


class Suggestion(BaseModel):
    """A before/after remediation suggestion."""

    finding_id: str
    location: str
    before: str
    after: str
    rationale: str
    source: FindingSource


class Report(BaseModel):
    """The full accessibility report for one uploaded document."""

    report_id: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    document: DocumentMeta
    blocks: list[Block] = Field(default_factory=list)
    findings: list[Finding] = Field(default_factory=list)
    suggestions: list[Suggestion] = Field(default_factory=list)
    summary: SummaryStats
    ai_available: bool = False
    ai_model: str | None = None
    notes: list[str] = Field(
        default_factory=lambda: [
            "This report is generated from a limited set of automated, "
            "rule-based checks. It does not certify WCAG conformance or "
            "PDF/UA validity. Review findings flagged for human review "
            "with a domain expert before publishing."
        ]
    )


class AssistantRequest(BaseModel):
    question: str = Field(..., min_length=1, max_length=8000)
    context: dict[str, Any] = Field(default_factory=dict)


class AssistantResponse(BaseModel):
    ok: bool
    answer: str
    model: str | None = None
    provider_configured: bool = False
    error: str | None = None


class UploadError(BaseModel):
    detail: str
